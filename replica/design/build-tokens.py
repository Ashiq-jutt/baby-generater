#!/usr/bin/env python3
"""Generate tokens.css, theme.ts and tailwind.config.js from tokens.json.

tokens.json is the single source of truth. Never hand-edit the outputs:
    python3 build-tokens.py && python3 contrast.py tokens.json
"""
import json, pathlib

HERE = pathlib.Path(__file__).parent
T = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
light, dark = T["color"]["light"], T["color"]["dark"]
ROLES = list(light)


def channels(hex_value):
    """#rrggbb -> "r g b" so Tailwind alpha modifiers (bg-accent/50) work."""
    h = hex_value.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    return " ".join(str(int(h[i:i + 2], 16)) for i in (0, 2, 4))

# ---------------------------------------------------------------- tokens.css
def block(colors, indent="  "):
    return "\n".join(f"{indent}--color-{k}: {v};" for k, v in colors.items())

css = [
    "/* GENERATED by build-tokens.py from tokens.json. Do not edit. */",
    ":root {",
    block(light),
    "",
]
for name, scale in T["type"].items():
    css.append(f'  --text-{name}: {scale["size"]}px;')
    css.append(f'  --leading-{name}: {scale["line"]}px;')
    css.append(f'  --weight-{name}: {scale["weight"]};')
css.append("")
for i, s in enumerate(T["space"]):
    css.append(f"  --space-{i}: {s}px;")
css.append("")
for k, v in T["radius"].items():
    css.append(f"  --radius-{k}: {v}px;")
for k, v in T["touch"].items():
    css.append(f"  --touch-{k}: {v}px;")
for k, v in T["layout"].items():
    css.append(f"  --layout-{k}: {v}px;")
for k, v in T["shadow"].items():
    css.append(f"  --shadow-{k}: {v};")
for k, v in T["motion"].items():
    css.append(f"  --motion-{k}: {v};")
css.append(f'  --font-sans: {T["font"]["sans"]};')
css.append(f'  --font-mono: {T["font"]["mono"]};')
css.append("}")
css.append("")
# dark mode: media query guarded so an explicit light theme wins, plus
# an explicit [data-theme=dark] hook
css.append("@media (prefers-color-scheme: dark) {")
css.append('  :root:not([data-theme="light"]) {')
css.append(block(dark, "    "))
css.append("  }")
css.append("}")
css.append("")
css.append(':root[data-theme="dark"] {')
css.append(block(dark))
css.append("}")
css.append("")
css.append("body { background: var(--color-bg); color: var(--color-text);")
css.append("  font-family: var(--font-sans); }")
(HERE / "tokens.css").write_text("\n".join(css) + "\n", encoding="utf-8")

# ----------------------------------------------------------------- theme.ts
ts = ["// GENERATED by build-tokens.py from tokens.json. Do not edit.",
      "// Runtime theme for React Native / Expo (NativeWind reads the Tailwind",
      "// config; this is for StyleSheet and animated values).", ""]
ts.append("export const light = " + json.dumps(light, indent=2) + " as const;")
ts.append("export const dark = " + json.dumps(dark, indent=2) + " as const;")
ts.append("export const type = " + json.dumps(T["type"], indent=2) + " as const;")
ts.append("export const space = " + json.dumps(T["space"]) + " as const;")
ts.append("export const radius = " + json.dumps(T["radius"], indent=2) + " as const;")
ts.append("export const touch = " + json.dumps(T["touch"], indent=2) + " as const;")
ts.append("export const layout = " + json.dumps(T["layout"], indent=2) + " as const;")
ts.append("export const motion = " + json.dumps(T["motion"], indent=2) + " as const;")
ts.append("")
ts.append("export type ColorRole = keyof typeof light;")
ts.append("export const themes = { light, dark } as const;")
(HERE / "theme.ts").write_text("\n".join(ts) + "\n", encoding="utf-8")

# ------------------------------------------------------------- global.css
# NativeWind v4 reads :root / .dark:root from the CSS entry file. Channel
# triplets (not hex) so `bg-accent/50` style alpha modifiers work on native.
def chan_block(colors, indent="    "):
    return "\n".join(
        f"{indent}--color-{k}: {channels(v)};" for k, v in colors.items())


gcss = [
    "/* GENERATED by replica/design/build-tokens.py. Do not edit. */",
    "@tailwind base;",
    "@tailwind components;",
    "@tailwind utilities;",
    "",
    "@layer base {",
    "  :root {",
    chan_block(light),
    "  }",
    "",
    "  /* explicit dark, set by NativeWind's colorScheme */",
    "  .dark:root, :root[data-theme=\"dark\"] {",
    chan_block(dark),
    "  }",
    "",
    "  /* system dark, unless an explicit light choice wins */",
    "  @media (prefers-color-scheme: dark) {",
    "    :root:not(.light):not([data-theme=\"light\"]) {",
    chan_block(dark, "      "),
    "    }",
    "  }",
    "}",
]
(HERE.parent.parent / "global.css").write_text("\n".join(gcss) + "\n", encoding="utf-8")

# -------------------------------------------------------- tailwind.config.js
colors = ",\n".join(
    f'        "{r}": "rgb(var(--color-{r}) / <alpha-value>)"' for r in ROLES)
fontsize = ",\n".join(
    f'        "{k}": ["{v["size"]}px", {{ lineHeight: "{v["line"]}px",'
    f' fontWeight: "{v["weight"]}" }}]' for k, v in T["type"].items())
spacing = ",\n".join(f'        "{i}": "{s}px"' for i, s in enumerate(T["space"]))
radii = ",\n".join(f'        "{k}": "{v}px"' for k, v in T["radius"].items())
tw = f"""// GENERATED by build-tokens.py from tokens.json. Do not edit.
// NativeWind v4 / Tailwind. Components use bg-surface, text-muted - never raw hex.
module.exports = {{
  content: ["./app/**/*.{{ts,tsx}}", "./components/**/*.{{ts,tsx}}", "./lib/**/*.{{ts,tsx}}"],
  presets: [require("nativewind/preset")],
  darkMode: "class",
  theme: {{
    extend: {{
      colors: {{
{colors}
      }},
      fontSize: {{
{fontsize}
      }},
      spacing: {{
{spacing}
      }},
      borderRadius: {{
{radii}
      }},
      minHeight: {{ touch: "{T['touch']['min']}px" }},
      minWidth: {{ touch: "{T['touch']['min']}px" }},
      fontFamily: {{ sans: [{json.dumps(T['font']['sans'])}] }},
    }},
  }},
  plugins: [],
}};
"""
(HERE / "tailwind.config.js").write_text(tw, encoding="utf-8")
print(f"wrote tokens.css, global.css, theme.ts, tailwind.config.js"
      f"  ({len(ROLES)} colour roles)")
